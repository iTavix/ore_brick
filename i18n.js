/* =====================================================================
   HourFlow — Lingua (IT / EN)
   L'italiano è la lingua sorgente: le stringhe nel codice restano in
   italiano e t() le traduce in inglese quando la lingua attiva è 'en'.
   Una stringa assente dal dizionario ricade sull'italiano (mai vuota).
   La scelta è per dispositivo (localStorage), non viene sincronizzata:
   Proprietario e Cliente possono usare lingue diverse.
   ===================================================================== */

const LANG_KEY = 'hf_lang';
let LANG = (function () {
  try { return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'it'; } catch (_) { return 'it'; }
})();

// t('Nota N. {n}', { n: '0001/2026' }) — i segnaposto {nome} vengono sostituiti
// DOPO la traduzione; i valori sono inseriti così come sono (già escapati da chi chiama).
function t(s, vars) {
  let out = (LANG === 'en' && Object.prototype.hasOwnProperty.call(I18N_EN, s)) ? I18N_EN[s] : s;
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return out;
}

function isEn() { return LANG === 'en'; }

// Locale per numeri e importi: en-GB → "€1,234.50", it-IT → "1.234,50 €".
function numLocale() { return LANG === 'en' ? 'en-GB' : 'it-IT'; }

// Testi statici di index.html: l'attributo data-i18n* conserva la sorgente italiana.
function applyStaticI18n() {
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  const btn = document.getElementById('lang-toggle');
  if (btn) {
    btn.textContent = LANG.toUpperCase();
    const hint = LANG === 'en' ? 'Language: English — switch to Italiano' : 'Lingua: Italiano — passa a English';
    btn.title = hint;
    btn.setAttribute('aria-label', hint);
  }
}

// Cambia lingua, la ricorda sul dispositivo e ridisegna la vista corrente.
function setLang(lang) {
  LANG = lang === 'en' ? 'en' : 'it';
  try { localStorage.setItem(LANG_KEY, LANG); } catch (_) {}
  applyStaticI18n();
  if (typeof updateSyncBadge === 'function') updateSyncBadge();
  if (typeof render === 'function') render();
}

